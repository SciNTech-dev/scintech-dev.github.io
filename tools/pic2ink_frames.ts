// Pic2Ink frames table for /pic2ink/compatibility/ (spec 0003 §4.3, §9.3, AC-7).
//
// Loads the app's own catalogue (DEVICES in src/lib/devices.ts of di2g/einksend, private) and
// writes the table between <!-- frames:begin --> and <!-- frames:end --> in the page, so the
// site never drifts from the catalogue. The einksend commit goes into the begin marker.
//
//   cd <einksend> && pnpm install --frozen-lockfile --ignore-scripts && pnpm exec svelte-kit sync
//   bun <site>/tools/pic2ink_frames.ts --einksend <einksend> --page <site>/pic2ink/compatibility/index.html [--check]
//
// --check writes nothing and exits 1 if the page's table differs from the generated one.
// Prints PIC2INK_FRAMES_OK nfc=<n> file=<n> tested=<n> commit=<sha> (or _FAIL / _WRITTEN).
//
// "Tested" is this list only, each entry with its evidence. A frame joins it only with a dated
// owner or tester confirmation recorded in docs/pic2ink-claims.md.
const TESTED: Record<string, string> = {
    'tapmora-sp6-photoframe': 'docs/TAPMORA.md: transfer verified on the owner\'s frame, 2026-10-28',
};

const INKS: Record<string, string> = {
    'bw': 'Black, white',
    'bwry': 'Black, white, red, yellow',
    'spectra-6': 'Spectra 6 (six inks)',
    'gray-4': '4 greys',
    'gray-16': '16 greys',
    'full-color': 'Full colour',
};

function arg(name: string): string | undefined {
    const i = process.argv.indexOf(name);
    return i > 0 ? process.argv[i + 1] : undefined;
}

const root = arg('--einksend');
const page = arg('--page');
const check = process.argv.includes('--check');
if (!root || !page) {
    console.log('PIC2INK_FRAMES_FAIL usage: --einksend DIR --page FILE [--check]');
    process.exit(2);
}

const git = Bun.spawnSync(['git', '-C', root, 'rev-parse', '--short=7', 'HEAD']);
const commit = git.stdout.toString().trim() || 'unknown';
const m = await import(root + '/src/lib/devices.ts');

const esc = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

type Row = { id: string; brand: string; model: string; inch: number; inks: string; px: string; nfc: boolean; tested: boolean };
const rows: Row[] = Object.values(m.DEVICES as Record<string, any>)
    .filter(d => d.id !== 'custom')
    .map(d => {
        const inks = INKS[d.paletteId];
        if (!inks) throw new Error(`no ink name for palette ${d.paletteId} (${d.id})`);
        return {
            id: d.id, brand: d.brand, model: m.getModelName(d), inch: d.inch, inks,
            px: `${d.width}&#215;${d.height}`, nfc: d.class?.name !== 'FileDevice', tested: d.id in TESTED,
        };
    });
for (const id of Object.keys(TESTED)) {
    if (!rows.some(r => r.id === id)) throw new Error(`tested id ${id} is not in the catalogue`);
}
rows.sort((a, b) => Number(b.tested) - Number(a.tested) || Number(b.nfc) - Number(a.nfc)
    || a.brand.localeCompare(b.brand) || a.inch - b.inch || a.model.localeCompare(b.model) || a.id.localeCompare(b.id));

const nfc = rows.filter(r => r.nfc).length;
const file = rows.length - nfc;
const tested = rows.filter(r => r.tested).length;

const body = rows.map(r => `            <tr${r.tested ? ' class="row-tested"' : ''}><td>${esc(r.brand)}</td><td>${esc(r.model)}</td><td>${r.inks}</td><td>${r.px}</td><td>${r.nfc ? 'NFC' : 'File (PNG)'}</td><td>${r.tested ? '<strong>Tested</strong>' : 'In catalogue, not tested with Pic2Ink'}</td></tr>`).join('\n');
const table = `<!-- frames:begin generated by tools/pic2ink_frames.ts from di2g/einksend src/lib/devices.ts @ ${commit}: nfc=${nfc} file=${file} tested=${tested} — do not edit by hand -->
        <div class="table-wrap">
          <table class="frames">
            <caption class="sr-only">Frames and displays in Pic2Ink's catalogue: ${nfc} NFC entries and ${file} file-export devices; ${tested} tested with Pic2Ink.</caption>
            <thead><tr><th scope="col">Brand</th><th scope="col">Model</th><th scope="col">Inks</th><th scope="col">Pixels</th><th scope="col">Connection</th><th scope="col">Status</th></tr></thead>
            <tbody>
${body}
            </tbody>
          </table>
        </div>
        <!-- frames:end -->`;

const html = await Bun.file(page).text();
const re = /<!-- frames:begin[^]*?<!-- frames:end -->/;
if (!re.test(html)) {
    console.log(`PIC2INK_FRAMES_FAIL ${page} has no frames:begin/end markers`);
    process.exit(1);
}
const current = html.match(re)![0];
if (check) {
    const ok = current === table;
    console.log(ok ? `PIC2INK_FRAMES_OK nfc=${nfc} file=${file} tested=${tested} commit=${commit}`
        : `PIC2INK_FRAMES_FAIL the table in ${page} differs from the catalogue at ${commit}`);
    process.exit(ok ? 0 : 1);
}
await Bun.write(page, html.replace(re, () => table));
console.log(`PIC2INK_FRAMES_WRITTEN nfc=${nfc} file=${file} tested=${tested} commit=${commit}`);
